<h2>Tanda dan Gejala Sifilis</h2>
<p>Gejala sifilis bervariasi tergantung pada tahapan atau stadium infeksi yang sedang dialami oleh penderita:</p>

<h3>A. Gejala Awal (Stadium Primer & Sekunder)</h3>
<ul class="daftar-info">
    <li><strong>Sifilis Primer:</strong> Muncul luka tunggal (disebut <em>chancre</em>) di area tempat bakteri masuk, biasanya di kelamin, anus, atau mulut. Luka ini berbentuk bulat, keras, tidak terasa nyeri, dan muncul sekitar 3 minggu setelah paparan.</li>
    <li><strong>Sifilis Sekunder:</strong> Beberapa minggu setelah luka awal sembuh, muncul ruam kemerahan atau kecokelatan pada kulit, terutama di telapak tangan dan telapak kaki. Ruam ini biasanya tidak terasa gatal.</li>
    <li><strong>Gejala Penyerta:</strong> Demam ringan, pembengkakan kelenjar getah bening, sakit tenggorokan, nyeri otot, kelelahan, serta rambut rontok tidak merata.</li>
</ul>

<h3>B. Gejala Lanjutan (Stadium Laten & Tersier)</h3>
<ul class="daftar-info">
    <li><strong>Sifilis Laten:</strong> Pada tahap ini seluruh gejala fisik menghilang sepenuhnya, namun bakteri tetap aktif di dalam tubuh. Tahap ini bisa berlangsung bertahun-tahun.</li>
    <li><strong>Sifilis Tersier (Tahap Akhir):</strong> Jika tidak diobati sama sekali, sekitar 15–30% penderita akan mengalami kerusakan serius pada organ dalam, meliputi:
        <ol class="daftar-info">
            <li>Gangguan saraf pusat dan otak (neurosifilis) yang memicu kelumpuhan, kebutaan, atau gangguan ingatan.</li>
            <li>Kerusakan pembuluh darah dan jantung (sifilis kardiovaskular).</li>
            <li>Munculnya benjolan lunak (<em>gumma</em>) pada kulit, tulang, atau organ hati.</li>
        </ol>
    </li>
</ul>

