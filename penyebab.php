<h2>Penyebab dan Cara Penularan</h2>

<h3>1. Penyebab Penyakit</h3>
<p>Penyebab utama sifilis adalah infeksi bakteri <strong><em>Treponema pallidum</em></strong>. Bakteri ini masuk ke dalam tubuh manusia melalui selaput lendir (mukosa) atau luka kecil (lecet mikroskopis) pada permukaan kulit saat terjadi kontak langsung dengan luka penderita.</p>

<h3>2. Cara Penularan</h3>
<ul class="daftar-info">
    <li><strong>Kontak Seksual Langsung:</strong> Penularan paling umum terjadi melalui hubungan seksual vaginal, anal, maupun oral dengan seseorang yang memiliki luka sifilis aktif.</li>
    <li><strong>Penularan dari Ibu ke Janin:</strong> Ibu hamil yang terinfeksi sifilis dapat menularkan bakteri melalui plasenta ke janin selama kehamilan atau saat proses persalinan.</li>
    <li><strong>Transfusi Darah & Jarum Suntik:</strong> Meskipun jarang karena proses skrining darah yang ketat, penularan dapat terjadi melalui penggunaan jarum suntik bersama atau produk darah yang terkontaminasi.</li>
</ul>

<div class="kotak-peringatan">
    <strong>Penting Diketahui:</strong> Sifilis <u>tidak menular</u> melalui penggunaan toilet duduk bersama, berenang di kolam renang umum, berbagi peralatan makan, maupun berjabat tangan.
</div>

<h3>3. Faktor Risiko Penularan</h3>
<ul class="daftar-info">
    <li>Melakukan hubungan seksual tanpa menggunakan pengaman (kondom).</li>
    <li>Berganti-ganti pasangan seksual.</li>
    <li>Memiliki riwayat infeksi menular seksual lainnya, seperti HIV atau gonore.</li>
    <li>Tidak melakukan pemeriksaan kesehatan (skrining IMS) secara berkala pada kelompok berisiko.</li>
</ul>

