<h2>Upaya Pencegahan Sifilis</h2>
<p>Hingga saat ini belum tersedia vaksin untuk mencegah sifilis. Oleh karena itu, langkah pencegahan difokuskan pada perilaku aman dan pola hidup sehat:</p>

<h3>1. Cara Mencegah Penularan</h3>
<ul class="daftar-info">
    <li><strong>Setia pada Satu Pasangan:</strong> Tidak berganti-ganti pasangan seksual dan memastikan pasangan juga tidak terinfeksi IMS.</li>
    <li><strong>Gunakan Pengaman:</strong> Menggunakan kondom lateks secara benar setiap kali melakukan hubungan seksual untuk mengurangi risiko kontak langsung dengan luka infeksi.</li>
    <li><strong>Skrining Ibu Hamil (Triple Eliminasi):</strong> Setiap ibu hamil wajib menjalani pemeriksaan darah sifilis pada kunjungan antenatal pertama untuk mencegah penularan ke bayi.</li>
</ul>

<h3>2. Perilaku Hidup Bersih dan Sehat (PHBS)</h3>
<ul class="daftar-info">
    <li>Menjaga kebersihan area organ reproduksi setiap hari menggunakan air bersih dan mengeringkannya dengan handuk bersih.</li>
    <li>Menghindari konsumsi alkohol berlebih dan narkoba, karena zat tersebut dapat menurunkan kesadaran dan memicu perilaku berisiko.</li>
    <li>Tidak menggunakan jarum suntik secara bergantian dalam kondisi apa pun.</li>
</ul>

<h3>3. Perlindungan Diri dan Lingkungan</h3>
<ul class="daftar-info">
    <li>Melakukan pemeriksaan kesehatan seksual (VCT / skrining IMS) secara rutin di Puskesmas atau klinik terdekat minimal 6 bulan sekali bagi yang aktif secara seksual.</li>
    <li>Segera mengajak pasangan untuk ikut diperiksa apabila salah satu dinyatakan positif terinfeksi, guna mencegah fenomena penularan berulang (efek ping-pong).</li>
</ul>

