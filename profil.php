<h2>Profil Penyakit Sifilis</h2>

<h3>1. Pengertian Sifilis</h3>
<p>Sifilis adalah penyakit infeksi menular seksual (IMS) yang bersifat kronis dan sistemik, disebabkan oleh bakteri berbentuk spiral bernama <em>Treponema pallidum</em>. Dalam sistem klasifikasi diagnosis medis (ICD-10), sifilis dikelompokkan dalam blok kode <strong>A50–A53</strong>.</p>

<h3>2. Karakteristik Penyakit</h3>
<ul class="daftar-info">
    <li><strong>Bersifat Bertahap:</strong> Perkembangan penyakit ini terbagi menjadi empat stadium utama, yaitu stadium primer, sekunder, laten, dan tersier.</li>
    <li><strong>Dijuluki "The Great Imitator":</strong> Sifilis sering disebut sebagai peniru ulung karena gejala ruam atau lukanya sering menyerupai penyakit kulit maupun penyakit infeksi lainnya.</li>
    <li><strong>Fase Laten Tanpa Gejala:</strong> Setelah gejala awal mereda, bakteri dapat bersembunyi di dalam tubuh selama bertahun-tahun tanpa menimbulkan keluhan fisik sebelum akhirnya masuk ke tahap lanjut.</li>
</ul>

<h3>3. Informasi Umum</h3>
<p>Sifilis tidak hanya menyerang area kelamin, tetapi juga dapat muncul di area mulut, bibir, atau dubur tergantung titik masuknya bakteri. Selain menular antar orang dewasa, sifilis juga sangat berbahaya bagi ibu hamil karena dapat menularkan infeksi kepada janin di dalam kandungan (sifilis kongenital).</p>

