<h2>Pemeriksaan dan Penanganan Medis</h2>

<h3>1. Informasi Pemeriksaan Penyakit</h3>
<p>Diagnosis sifilis tidak bisa hanya dilihat dari gejala luar, melainkan harus dipastikan melalui pemeriksaan laboratorium di fasilitas kesehatan, antara lain:</p>
<ul class="daftar-info">
    <li><strong>Tes Darah Serologi:</strong> Pemeriksaan screening seperti VDRL atau RPR untuk mendeteksi antibodi umum, serta tes konfirmasi spesifik seperti TPHA atau TP-Rapid.</li>
    <li><strong>Pemeriksaan Cairan Luka:</strong> Mengambil sampel cairan dari luka <em>chancre</em> untuk diamati langsung di bawah mikroskop lapangan gelap.</li>
</ul>

<h3>2. Penanganan dan Pengobatan Medis</h3>
<ul class="daftar-info">
    <li><strong>Pemberian Antibiotik:</strong> Pengobatan utama sifilis adalah suntikan antibiotik golongan penisilin (<em>Benzathine penicillin G</em>) dengan dosis yang disesuaikan dengan stadium penyakit oleh dokter.</li>
    <li><strong>Pasien Alergi Penisilin:</strong> Bagi pasien yang memiliki alergi terhadap penisilin, dokter akan memberikan antibiotik alternatif seperti doksisiklin atau azitromisin.</li>
    <li><strong>Pantangan Selama Pengobatan:</strong> Pasien dilarang melakukan kontak seksual hingga pengobatan selesai tuntas dan luka dinyatakan sembuh total oleh dokter.</li>
</ul>

<h3>3. Anjuran Pelayanan Kesehatan</h3>
<p>Jangan pernah membeli obat antibiotik sendiri tanpa resep dokter atau menggunakan obat-obatan herbal yang tidak teruji secara klinis. Segera kunjungi <strong>Puskesmas, Klinik IMS, atau Rumah Sakit terdekat</strong> agar mendapatkan pemeriksaan yang akurat, rahasia, dan pengobatan yang tepat.</p>

